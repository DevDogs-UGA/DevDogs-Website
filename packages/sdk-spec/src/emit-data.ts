/**
 * Emitters for the spec files that are plain data rather than schemas: the
 * shared constants, the brand tokens and the telemetry scrub rules.
 */
import { DART_BANNER } from "./emit-dart.js";
import { camelCase, constantCase, dartString, tsString } from "./names.js";

type Json = Record<string, unknown>;

function isObject(value: unknown): value is Json {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

function tsHeader(source: string): string {
  return `// @generated by @devdogsuga/sdk-spec from ${source} — do not edit by hand.\n// Run \`pnpm -F @devdogsuga/sdk-spec codegen\` after changing the spec.\n`;
}

// ── constants ───────────────────────────────────────────────────────────────

export function constantsTs(constants: Json): string {
  const parts = [tsHeader("constants.json")];
  for (const [key, value] of Object.entries(constants)) {
    if (key.startsWith("$")) continue;
    parts.push(
      `export const ${constantCase(key)} = ${JSON.stringify(value, null, 2)} as const;\n`,
    );
  }
  return parts.join("\n");
}

function dartScalar(value: unknown): { type: string; literal: string } {
  if (typeof value === "string")
    return { type: "String", literal: dartString(value) };
  if (typeof value === "boolean")
    return { type: "bool", literal: String(value) };
  if (typeof value === "number") {
    return Number.isInteger(value)
      ? { type: "int", literal: String(value) }
      : { type: "double", literal: String(value) };
  }
  throw new Error(`Unsupported constant ${JSON.stringify(value)}`);
}

function flatten(prefix: string, value: unknown, out: string[]): void {
  if (isObject(value)) {
    for (const [key, child] of Object.entries(value)) {
      if (key.startsWith("$")) continue;
      flatten(`${prefix}_${key}`, child, out);
    }
    return;
  }
  const name = camelCase(prefix);
  if (Array.isArray(value)) {
    const items = value.map(dartScalar);
    const type = items[0]?.type ?? "String";
    out.push(
      `const List<${type}> ${name} = [${items.map((i) => i.literal).join(", ")}];`,
    );
    return;
  }
  const scalar = dartScalar(value);
  out.push(`const ${scalar.type} ${name} = ${scalar.literal};`);
}

export function constantsDart(constants: Json): string {
  const lines: string[] = [];
  for (const [key, value] of Object.entries(constants)) {
    if (key.startsWith("$")) continue;
    flatten(key, value, lines);
  }
  return `${DART_BANNER("constants.json")}\n${lines.join("\n\n")}\n`;
}

// ── brand tokens ────────────────────────────────────────────────────────────

function dartColor(hex: unknown): string {
  if (typeof hex !== "string" || !/^#[0-9a-fA-F]{6}$/.test(hex)) {
    throw new Error(`Not a #rrggbb colour: ${String(hex)}`);
  }
  return `Color(0xFF${hex.slice(1).toLowerCase()})`;
}

function record(value: unknown, what: string): Json {
  if (!isObject(value)) throw new Error(`${what} should be an object`);
  return value;
}

export function brandTokensDart(tokens: Json): string {
  const palette = record(tokens["palette"], "palette");
  const theme = record(tokens["theme"], "theme");
  const apps = record(tokens["apps"], "apps");
  const marks = record(tokens["marks"], "marks");
  const contact = record(tokens["contact"], "contact");
  const shadow = record(tokens["blockShadow"], "blockShadow");
  const metrics = record(tokens["wordmarkMetrics"], "wordmarkMetrics");
  const fonts = (tokens["fonts"] as Json[] | undefined) ?? [];
  const artwork = (tokens["artwork"] as string[] | undefined) ?? [];

  const out: string[] = [DART_BANNER("brand/tokens.json")];
  out.push(`import 'dart:ui' show Color;\n`);

  out.push(
    `/// The club palette, flat sRGB. Names follow \`--brand-*\` in palette.css.\nabstract final class BrandPalette {\n${Object.entries(
      palette,
    )
      .map(
        ([name, hex]) =>
          `  static const Color ${camelCase(name)} = ${dartColor(hex)};`,
      )
      .join("\n")}\n}\n`,
  );

  out.push(
    `/// The roles the palette plays in the dark theme the club's images use.\nabstract final class BrandTheme {\n${Object.entries(
      theme,
    )
      .map(
        ([name, hex]) =>
          `  static const Color ${camelCase(name)} = ${dartColor(hex)};`,
      )
      .join("\n")}\n}\n`,
  );

  out.push(
    `/// How far a block shadow is thrown, in logical pixels.\nabstract final class BrandBlockShadow {\n${Object.entries(
      shadow,
    )
      .map(
        ([name, n]) =>
          `  static const double ${camelCase(name)} = ${String(n)};`,
      )
      .join("\n")}\n}\n`,
  );

  out.push(
    `/// Where the club is.\nabstract final class BrandContact {\n${Object.entries(
      contact,
    )
      .map(
        ([name, v]) =>
          `  static const String ${camelCase(name)} = ${dartString(String(v))};`,
      )
      .join("\n")}\n}\n`,
  );

  out.push(
    `/// The wordmark's cap height and baseline as fractions of its height.\nabstract final class BrandWordmarkMetrics {\n${Object.entries(
      metrics,
    )
      .map(
        ([name, n]) =>
          `  static const double ${camelCase(name)} = ${String(n)};`,
      )
      .join("\n")}\n}\n`,
  );

  out.push(
    `/// One of the club's apps: its name, copy, host and the colours of its tile.\nclass AppBrand {\n  const AppBrand({\n    required this.name,\n    required this.tagline,\n    required this.blurb,\n    required this.host,\n    required this.ground,\n    required this.mark,\n  });\n\n  final String name;\n  final String tagline;\n  final String blurb;\n  final String host;\n\n  /// The tile fill.\n  final Color ground;\n\n  /// The mark's colour when drawn on [ground].\n  final Color mark;\n}\n`,
  );
  out.push(
    `abstract final class BrandApps {\n${Object.entries(apps)
      .map(([key, raw]) => {
        const app = record(raw, `apps.${key}`);
        return `  static const AppBrand ${camelCase(key)} = AppBrand(\n    name: ${dartString(String(app["name"]))},\n    tagline: ${dartString(String(app["tagline"]))},\n    blurb: ${dartString(String(app["blurb"]))},\n    host: ${dartString(String(app["host"]))},\n    ground: ${dartColor(app["ground"])},\n    mark: ${dartColor(app["mark"])},\n  );`;
      })
      .join("\n\n")}\n\n  static const List<AppBrand> all = [${Object.keys(apps)
      .map(camelCase)
      .join(", ")}];\n}\n`,
  );

  out.push(
    `/// The DogDays and DogPack marks as SVG. Paint is \`currentColor\`: render\n/// with a colour filter or replace it before handing the string to an SVG\n/// widget.\nabstract final class BrandMarks {\n${Object.entries(
      marks,
    )
      .map(
        ([name, svg]) =>
          `  static const String ${camelCase(name)} = ${dartString(String(svg))};`,
      )
      .join("\n")}\n}\n`,
  );

  out.push(
    `/// A font face the SDK ships under \`assets/fonts\`. Apps opt in from their\n/// own pubspec; see the package README.\nclass BrandFont {\n  const BrandFont({\n    required this.family,\n    required this.weight,\n    required this.asset,\n  });\n\n  final String family;\n  final int weight;\n\n  /// The asset key to declare in the app's pubspec.\n  final String asset;\n}\n`,
  );
  out.push(
    `abstract final class BrandFonts {\n  static const List<BrandFont> all = [\n${fonts
      .map(
        (f) =>
          `    BrandFont(\n      family: ${dartString(String(f["family"]))},\n      weight: ${String(f["weight"])},\n      asset: ${dartString(`packages/devdogsuga_sdk/assets/fonts/${String(f["file"])}`)},\n    ),`,
      )
      .join("\n")}\n  ];\n}\n`,
  );

  out.push(
    `/// The artwork under \`assets/brand\`, by file name.\nabstract final class BrandArtwork {\n${artwork
      .map(
        (file) =>
          `  static const String ${camelCase(file.replace(/\.[^.]+$/, ""))} = ${dartString(`packages/devdogsuga_sdk/assets/brand/${file}`)};`,
      )
      .join("\n")}\n}\n`,
  );

  return out.join("\n");
}

// ── telemetry scrub rules ───────────────────────────────────────────────────

export function scrubRulesDart(file: Json): string {
  const rules = (file["rules"] as Json[] | undefined) ?? [];
  return `${DART_BANNER("telemetry/scrub.json")}
/// One text scrubber: a pattern and what replaces each match.
///
/// [replacement] is a JavaScript replacement string; \`$1\` is the first
/// capture group. The patterns are ECMAScript, which Dart's [RegExp] reads.
class ScrubRule {
  const ScrubRule(this.name, this.pattern, this.replacement);

  final String name;
  final String pattern;
  final String replacement;
}

/// In the order they are applied.
const List<ScrubRule> scrubRules = [
${rules
  .map(
    (r) =>
      `  ScrubRule(${dartString(String(r["name"]))}, ${dartString(String(r["pattern"]))}, ${dartString(String(r["replacement"]))}),`,
  )
  .join("\n")}
];
`;
}

