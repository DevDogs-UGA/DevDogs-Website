/**
 * Writes the TypeScript side of a spec: one interface or union per
 * declaration, plus (for specs with operations that carry no signing) a client
 * factory over `../client/http.ts`.
 */
import { camelCase, constantCase, jsDoc, tsString } from "./names.js";
import type { Decl, Operation, Param, Spec, Type } from "./spec.js";

export function tsType(type: Type): string {
  switch (type.kind) {
    case "string":
    case "integer":
    case "number":
    case "boolean":
      return type.kind === "integer" ? "number" : type.kind;
    case "unknown":
      return "unknown";
    case "array": {
      const item = tsType(type.item);
      return item.includes(" ") ? `(${item})[]` : `${item}[]`;
    }
    case "record":
      return `Record<string, ${tsType(type.value)}>`;
    case "ref":
      return type.name;
    case "nullable":
      return `${tsType(type.inner)} | null`;
  }
}

function propKey(name: string): string {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) ? name : tsString(name);
}

export function emitDecl(decl: Decl): string {
  const doc = jsDoc(decl.doc);
  switch (decl.kind) {
    case "object": {
      const props = decl.props
        .map(
          (p) =>
            `${jsDoc(p.doc, "  ")}  ${propKey(p.name)}${p.required ? "" : "?"}: ${tsType(p.type)};`,
        )
        .join("\n");
      return `${doc}export interface ${decl.name} {\n${props}\n}\n`;
    }
    case "enum": {
      const values = decl.values.map(tsString);
      return `${doc}export const ${constantCase(decl.name)}_VALUES = [${values.join(", ")}] as const;\nexport type ${decl.name} = (typeof ${constantCase(decl.name)}_VALUES)[number];\n`;
    }
    case "union":
      return `${doc}export type ${decl.name} = ${decl.members.join(" | ")};\n`;
    case "alias":
      return `${doc}export type ${decl.name} = ${tsType(decl.type)};\n`;
  }
}

function paramType(param: Param): string {
  return tsType(param.type);
}

function operationParams(op: Operation): Param[] {
  // Header parameters are the caller's business (the client sets `X-Client`).
  return op.params.filter((p) => p.in !== "header");
}

function emitOperation(op: Operation): { signature: string; impl: string } {
  const params = operationParams(op);
  const hasParams = params.length > 0;
  const requiredParams = params.some((p) => p.required);
  const argName = "params";
  const paramsType = hasParams
    ? `{ ${params
        .map(
          (p) => `${propKey(p.name)}${p.required ? "" : "?"}: ${paramType(p)}`,
        )
        .join("; ")} }`
    : "";
  const args = hasParams
    ? `${argName}${requiredParams ? "" : "?"}: ${paramsType}, `
    : "";
  const result = op.success ? tsType(op.success.type) : "void";
  const doc = jsDoc(
    [op.summary, op.doc].filter(Boolean).join("\n\n") || undefined,
    "  ",
  );
  const signature = `${doc}  ${op.id}(${args}options?: RequestOptions): Promise<${result}>;`;

  const pathParams = params.filter((p) => p.in === "path");
  const queryParams = params.filter((p) => p.in === "query");
  let path = tsString(op.path);
  if (pathParams.length > 0) {
    const templ = op.path.replace(
      /\{([^}]+)\}/g,
      (_m, name: string) =>
        `\${encodeURIComponent(String(${argName}.${name}))}`,
    );
    path = `\`${templ}\``;
  }
  const query =
    queryParams.length > 0
      ? `, query: { ${queryParams
          .map(
            (p) =>
              `${propKey(p.name)}: ${argName}${requiredParams ? "" : "?"}.${p.name}`,
          )
          .join(", ")} }`
      : "";
  const impl = `    ${op.id}: (${hasParams ? `${argName}, ` : ""}options) =>\n      request<${result}>(config, { method: ${tsString(op.method.toUpperCase())}, path: ${path}${query} }, options),`;
  return { signature, impl };
}

export interface TsOutputOptions {
  /** Where the file says it came from. */
  source: string;
  /** Prefix for the client names: `Catalog` gives `CatalogClient`. */
  clientName?: string;
  /** Subpath of the shared HTTP runtime. */
  runtimeImport?: string;
}

export function emitTs(spec: Spec, options: TsOutputOptions): string {
  const header = `// @generated by @devdogsuga/sdk-spec from ${options.source} — do not edit by hand.\n// Run \`pnpm -F @devdogsuga/sdk-spec generate\` after changing the spec.\n`;
  const parts: string[] = [header];

  const clientOps = spec.ops.filter((op) => op.client);
  const name = options.clientName;
  if (name && clientOps.length > 0) {
    parts.push(
      `import { request, type ClientConfig, type RequestOptions } from "${options.runtimeImport ?? "../client/http.js"}";\n`,
    );
  }

  if (spec.servers.length > 0) {
    const entries = spec.servers
      .map((s) => `  ${propKey(camelCase(s.key))}: ${tsString(s.url)},`)
      .join("\n");
    parts.push(
      `/** The servers the spec lists. */\nexport const ${constantCase(name ?? "api")}_SERVERS = {\n${entries}\n} as const;\n`,
    );
  }

  for (const decl of spec.decls) parts.push(emitDecl(decl));

  if (name && clientOps.length > 0) {
    const emitted = clientOps.map(emitOperation);
    parts.push(
      `export interface ${name}Client {\n${emitted.map((e) => e.signature).join("\n")}\n}\n`,
    );
    parts.push(
      `/** A client for the ${name.toLowerCase()} API. \`config.baseUrl\` is required: read it from the environment, never hard-code a server. */\nexport function create${name}Client(config: ClientConfig): ${name}Client {\n  return {\n${emitted.map((e) => e.impl).join("\n")}\n  };\n}\n`,
    );
  }

  return parts.join("\n");
}
