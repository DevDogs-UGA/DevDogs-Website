/**
 * `db types`: the generated TypeScript types or Dart models for a product's
 * schema. Never committed (Q82); three ways to have them:
 *
 *   * generate them from the contributor's own database (`db types`);
 *   * download the asset CI built for the exact schema hash
 *     (`db types --download`), which needs no database at all;
 *   * pack what was generated into that asset (`db types --pack file.tgz`),
 *     which is what CI does on every schema change on `main`.
 */
import {
  existsSync,
  mkdirSync,
  readFileSync,
  renameSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { basename, dirname, join, resolve } from "node:path";
import type { Product } from "./config.js";
import type { Runner } from "./exec.js";
import { generatorFor, schemaHashFor, typesAssetName } from "./schema-hash.js";
import { cliLine, type SupabaseCli } from "./supabase-cli.js";
import type { DbTarget } from "./target.js";

export class TypesError extends Error {
  constructor(
    message: string,
    readonly output?: string,
  ) {
    super(message);
    this.name = "TypesError";
  }
}

export interface TypesState {
  hash: string;
  generator: string;
  source: "generated" | "downloaded";
  at: string;
}

export function readTypesState(product: Product): TypesState | null {
  try {
    return JSON.parse(
      readFileSync(product.paths.stateFile, "utf8"),
    ) as TypesState;
  } catch {
    return null;
  }
}

function writeTypesState(product: Product, state: TypesState): void {
  mkdirSync(dirname(product.paths.stateFile), { recursive: true });
  writeFileSync(product.paths.stateFile, `${JSON.stringify(state, null, 2)}\n`);
}

/** Whether the types on disk were made from the schema as it is now. */
export function typesAreCurrent(product: Product): boolean {
  const state = readTypesState(product);
  return (
    state !== null &&
    existsSync(join(product.root, product.config.types.out)) &&
    state.hash === schemaHashFor(product)
  );
}

function redact(output: string, secret: string): string {
  return secret.length > 0 ? output.split(secret).join("<DB_URL>") : output;
}

export async function generateTypes(
  product: Product,
  cli: SupabaseCli,
  target: DbTarget,
  run: Runner,
  log: (line: string) => void = () => undefined,
): Promise<TypesState> {
  const { types, supabase } = product.config;
  const out = join(product.root, types.out);
  const hash = schemaHashFor(product);

  if (types.kind === "typescript") {
    const args = [
      ...cli.prefix,
      "gen",
      "types",
      "typescript",
      ...(target.kind === "local" ? ["--local"] : ["--db-url", target.dbUrl]),
      "--schema",
      supabase.schemas.join(","),
    ];
    // The connection string carries the database password; the terminal
    // (which people screenshot for help) shows a placeholder instead.
    const shown = args
      .slice(cli.prefix.length)
      .map((arg) => (arg === target.dbUrl ? "<DB_URL>" : arg));
    log(`Running ${cliLine(cli, shown)}`);
    const result = await run(cli.command, args, { cwd: product.root });
    if (result.code !== 0 || result.stdout.trim().length === 0) {
      throw new TypesError(
        "The Supabase CLI could not generate types. Is the database up and synced (`devtools db sync`)?",
        redact(result.stderr || result.stdout, target.dbUrl),
      );
    }
    mkdirSync(dirname(out), { recursive: true });
    writeFileSync(
      out,
      `// @generated by \`devtools db types\` (${generatorFor(product)}) from supabase/schemas, hash ${hash.slice(0, 12)}. Not committed.\n${result.stdout}`,
    );
  } else {
    log("Running dart run supadart");
    const result = await run("dart", ["run", "supadart"], {
      cwd: product.root,
      env: { SUPABASE_URL: target.apiUrl, SUPABASE_API_KEY: target.secretKey },
    });
    if (result.code !== 0) {
      throw new TypesError(
        "supadart could not generate the models. It needs Dart on PATH, `dart pub get` run once, and a synced database.",
        result.stderr || result.stdout,
      );
    }
    if (!existsSync(out)) {
      throw new TypesError(
        `supadart ran but ${types.out} does not exist; check that ${types.config} writes its output there.`,
      );
    }
  }

  const state: TypesState = {
    hash,
    generator: generatorFor(product),
    source: "generated",
    at: new Date().toISOString(),
  };
  writeTypesState(product, state);
  return state;
}

// ── packing and downloading ─────────────────────────────────────────────────

/** `tar` the generated output into one asset, named for the hash by the caller. */
export async function packTypes(
  product: Product,
  file: string,
  run: Runner,
): Promise<void> {
  const out = join(product.root, product.config.types.out);
  if (!existsSync(out)) {
    throw new TypesError(
      `${product.config.types.out} does not exist; run \`devtools db types\` first.`,
    );
  }
  // The archive is named relative to the working directory, never by an
  // absolute path: GNU tar (the one in Git for Windows' PATH) reads the colon in
  // `D:\...` as `host:file` and fails with "Cannot connect to D".
  const archive = resolve(product.root, file);
  const result = await run(
    "tar",
    ["-czf", basename(archive), "-C", dirname(out), basename(out)],
    { cwd: dirname(archive) },
  );
  if (result.code !== 0) {
    throw new TypesError("tar could not write the asset.", result.stderr);
  }
}

interface ReleaseAsset {
  name: string;
  browser_download_url: string;
}

export interface DownloadDeps {
  fetch: typeof fetch;
  run: Runner;
  /** `GITHUB_TOKEN`, to lift the anonymous API rate limit. */
  token?: string | undefined;
}

export async function downloadTypes(
  product: Product,
  deps: DownloadDeps,
  log: (line: string) => void = () => undefined,
): Promise<TypesState> {
  const source = product.config.generatedTypes;
  if (!source) {
    throw new TypesError(
      "This product publishes no generated types (no `generatedTypes` in devtools.config.json). Run `devtools db types` against a synced database instead.",
    );
  }
  const hash = schemaHashFor(product);
  const wanted = typesAssetName(product.config.product, hash);
  const headers: Record<string, string> = {
    accept: "application/vnd.github+json",
    "user-agent": "devdogsuga-devtools",
  };
  if (deps.token) headers["authorization"] = `Bearer ${deps.token}`;

  log(`Looking for ${wanted} in ${source.repo}@${source.tag}`);
  const release = await deps.fetch(
    `https://api.github.com/repos/${source.repo}/releases/tags/${source.tag}`,
    { headers },
  );
  if (!release.ok) {
    throw new TypesError(
      `Could not read the ${source.tag} release of ${source.repo} (${release.status}). Run \`devtools setup\` to generate the types from your own database instead.`,
    );
  }
  const body = (await release.json()) as { assets?: ReleaseAsset[] };
  const asset = body.assets?.find((a) => a.name === wanted);
  if (!asset) {
    throw new TypesError(
      `There are no generated types for your schema yet (hash ${hash.slice(0, 12)}). CI builds them when a schema change lands on main; until then run \`devtools setup\` to generate them from your own database.`,
    );
  }

  const download = await deps.fetch(asset.browser_download_url, {
    headers: { "user-agent": "devdogsuga-devtools" },
  });
  if (!download.ok) {
    throw new TypesError(`Downloading ${wanted} failed (${download.status}).`);
  }
  const out = join(product.root, product.config.types.out);
  const staging = join(product.root, ".devtools", "download");
  rmSync(staging, { recursive: true, force: true });
  mkdirSync(staging, { recursive: true });
  const archive = join(staging, wanted);
  writeFileSync(archive, Buffer.from(await download.arrayBuffer()));
  // Run in `staging` and name the archive relatively: see packTypes.
  const extracted = await deps.run("tar", ["-xzf", wanted], { cwd: staging });
  if (extracted.code !== 0) {
    throw new TypesError(
      "tar could not read the downloaded asset.",
      extracted.stderr,
    );
  }
  const unpacked = join(staging, basename(out));
  if (!existsSync(unpacked)) {
    throw new TypesError(`The asset does not contain ${basename(out)}.`);
  }
  rmSync(out, { recursive: true, force: true });
  mkdirSync(dirname(out), { recursive: true });
  renameSync(unpacked, out);
  rmSync(staging, { recursive: true, force: true });

  const state: TypesState = {
    hash,
    generator: generatorFor(product),
    source: "downloaded",
    at: new Date().toISOString(),
  };
  writeTypesState(product, state);
  return state;
}
