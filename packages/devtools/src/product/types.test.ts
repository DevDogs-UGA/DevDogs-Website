import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { describe, expect, it } from "vitest";
import { CLI, makeProduct, recordingRunner, writeFiles } from "./fixtures.js";
import { schemaHashFor, typesAssetName } from "./schema-hash.js";
import type { DbTarget } from "./target.js";
import {
  downloadTypes,
  generateTypes,
  packTypes,
  readTypesState,
  TypesError,
  typesAreCurrent,
} from "./types.js";

const LOCAL: DbTarget = {
  kind: "local",
  apiUrl: "http://127.0.0.1:54321",
  dbUrl: "postgresql://postgres:postgres@127.0.0.1:54322/postgres",
  publishableKey: "p",
  secretKey: "sb_secret_s",
};

describe("generateTypes (TypeScript)", () => {
  it("runs gen types against the stack and writes the output with a header", async () => {
    const product = makeProduct();
    const { run, calls } = recordingRunner(() => ({
      stdout: "export type Json = unknown;\n",
    }));
    const state = await generateTypes(product, CLI, LOCAL, run);

    expect(calls[0]?.args).toEqual([
      "gen",
      "types",
      "typescript",
      "--local",
      "--schema",
      "dogpack",
    ]);
    const out = readFileSync(
      join(product.root, "lib/database.types.ts"),
      "utf8",
    );
    expect(out).toContain(
      "@generated by `devtools db types` (supabase@2.117.0)",
    );
    expect(out).toContain("export type Json = unknown;");
    expect(state.hash).toBe(schemaHashFor(product));
    expect(readTypesState(product)?.source).toBe("generated");
    expect(typesAreCurrent(product)).toBe(true);
  });

  it("uses --db-url for a hosted project and joins several schemas", async () => {
    const product = makeProduct({
      config: {
        supabase: { version: "2.117.0", schemas: ["public", "dogdays"] },
      },
    });
    const { run, calls } = recordingRunner(() => ({ stdout: "x" }));
    const hosted: DbTarget = {
      ...LOCAL,
      kind: "hosted",
      dbUrl: "postgresql://h",
    };
    await generateTypes(product, CLI, hosted, run);
    expect(calls[0]?.args).toEqual([
      "gen",
      "types",
      "typescript",
      "--db-url",
      "postgresql://h",
      "--schema",
      "public,dogdays",
    ]);
  });

  it("stops being current when the schema changes", async () => {
    const product = makeProduct();
    const { run } = recordingRunner(() => ({ stdout: "x" }));
    await generateTypes(product, CLI, LOCAL, run);
    writeFiles(product.root, {
      "supabase/schemas/dogpack/tables/new.sql": "create table dogpack.n ();\n",
    });
    expect(typesAreCurrent(product)).toBe(false);
  });

  it("does not write a file when the CLI fails", async () => {
    const product = makeProduct();
    const { run } = recordingRunner(() => ({ code: 1, stderr: "boom" }));
    await expect(generateTypes(product, CLI, LOCAL, run)).rejects.toThrow(
      TypesError,
    );
    expect(existsSync(join(product.root, "lib/database.types.ts"))).toBe(false);
  });
});

describe("generateTypes (supadart)", () => {
  const dart = {
    config: { types: { kind: "supadart", out: "lib/generated" } },
  };

  it("runs dart run supadart with the target's URL and secret key", async () => {
    const product = makeProduct(dart);
    const { run, calls } = recordingRunner(({ command }) => {
      if (command === "dart") {
        writeFiles(product.root, {
          "lib/generated/session.dart": "class Session {}\n",
        });
      }
      return undefined;
    });
    await generateTypes(product, CLI, LOCAL, run);
    expect(calls[0]?.command).toBe("dart");
    expect(calls[0]?.args).toEqual(["run", "supadart"]);
    expect(calls[0]?.options.env).toEqual({
      SUPABASE_URL: "http://127.0.0.1:54321",
      SUPABASE_API_KEY: "sb_secret_s",
    });
  });

  it("fails if supadart wrote nothing where the config says", async () => {
    const product = makeProduct(dart);
    const { run } = recordingRunner();
    await expect(generateTypes(product, CLI, LOCAL, run)).rejects.toThrow(
      /does not exist/,
    );
  });
});

describe("packTypes", () => {
  it("tars the output beside its parent", async () => {
    const product = makeProduct();
    writeFiles(product.root, { "lib/database.types.ts": "x" });
    const { run, calls } = recordingRunner();
    await packTypes(product, "out.tgz", run);
    expect(calls[0]?.command).toBe("tar");
    expect(calls[0]?.args).toEqual([
      "-czf",
      "out.tgz",
      "-C",
      join(product.root, "lib"),
      "database.types.ts",
    ]);
  });

  it("asks for generation first when there is nothing to pack", async () => {
    const product = makeProduct();
    const { run } = recordingRunner();
    await expect(packTypes(product, "out.tgz", run)).rejects.toThrow(
      /db types/,
    );
  });
});

describe("downloadTypes", () => {
  function fakeGitHub(
    product: ReturnType<typeof makeProduct>,
    assets: string[],
  ) {
    const seen: string[] = [];
    const impl: typeof fetch = (input, init) => {
      const url = typeof input === "string" ? input : "";
      seen.push(`${url} ${JSON.stringify(init?.headers ?? {})}`);
      if (url.startsWith("https://api.github.com/")) {
        return Promise.resolve(
          Response.json({
            assets: assets.map((name) => ({
              name,
              browser_download_url: `https://example.test/${name}`,
            })),
          }),
        );
      }
      return Promise.resolve(new Response(new Uint8Array([1, 2, 3])));
    };
    const { run, calls } = recordingRunner(({ command, args }) => {
      // Stand in for `tar -xzf archive -C staging`: put the file there.
      if (command === "tar") {
        const staging = String(args[args.indexOf("-C") + 1]);
        mkdirSync(staging, { recursive: true });
        writeFileSync(join(staging, "database.types.ts"), "// downloaded\n");
      }
      return undefined;
    });
    return { impl, run, calls, seen, product };
  }

  it("finds the asset for the schema hash and unpacks it into place", async () => {
    const product = makeProduct();
    const wanted = typesAssetName("dogpack", schemaHashFor(product));
    const { impl, run, seen } = fakeGitHub(product, ["other.tgz", wanted]);
    const state = await downloadTypes(product, {
      fetch: impl,
      run,
      token: "ghp_test",
    });

    expect(seen[0]).toContain(
      "repos/DevDogsUGA/DogPack/releases/tags/generated-types",
    );
    expect(seen[0]).toContain("Bearer ghp_test");
    expect(seen[1]).toContain(`https://example.test/${wanted}`);
    expect(
      readFileSync(join(product.root, "lib/database.types.ts"), "utf8"),
    ).toBe("// downloaded\n");
    expect(state.source).toBe("downloaded");
    expect(typesAreCurrent(product)).toBe(true);
    expect(existsSync(join(product.root, ".devtools", "download"))).toBe(false);
  });

  it("says CI has not built them yet when there is no asset for this hash", async () => {
    const product = makeProduct();
    const { impl, run } = fakeGitHub(product, [
      "dogpack-types-someoneelses.tgz",
    ]);
    await expect(downloadTypes(product, { fetch: impl, run })).rejects.toThrow(
      /no generated types for your schema yet/,
    );
  });

  it("points at setup when the release cannot be read", async () => {
    const product = makeProduct();
    const { run } = recordingRunner();
    const impl: typeof fetch = () =>
      Promise.resolve(new Response("nope", { status: 404 }));
    await expect(downloadTypes(product, { fetch: impl, run })).rejects.toThrow(
      /devtools setup/,
    );
  });

  it("refuses for a product that publishes none", async () => {
    const product = makeProduct();
    const without = {
      ...product,
      config: { ...product.config, generatedTypes: undefined },
    };
    const { run } = recordingRunner();
    await expect(
      downloadTypes(without, {
        fetch: () => Promise.reject(new Error("no")),
        run,
      }),
    ).rejects.toThrow(/publishes no generated types/);
  });

  it("does not need a token", async () => {
    const product = makeProduct();
    const wanted = typesAssetName("dogpack", schemaHashFor(product));
    const { impl, run, seen } = fakeGitHub(product, [wanted]);
    await downloadTypes(product, { fetch: impl, run });
    expect(seen[0]).not.toContain("authorization");
    void dirname;
  });
});
