// Writes src/generated/theme-images.ts: every theme PNG under the platform's
// public/brand/newsletter/theme/ as base64, so a send can carry them as inline
// cid: parts (the one image form both Outlooks show without a "download
// pictures" click) instead of linking to devdogsuga.org. Run after
// build-theme-assets.py: `node tools/embed-theme-images.mjs`.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
const here = dirname(fileURLToPath(import.meta.url));
const dir = join(here, "../../../apps/platform/public/brand/newsletter/theme");
const names = readdirSync(dir)
  .filter((f) => f.endsWith(".png"))
  .sort();
const body = names
  .map(
    (f) =>
      `  "${f.slice(0, -4)}":\n    "${readFileSync(join(dir, f)).toString("base64")}",`,
  )
  .join("\n");
writeFileSync(
  join(here, "../src/generated/theme-images.ts"),
  `// Generated by tools/embed-theme-images.mjs from apps/platform/public/brand/newsletter/theme/. Do not edit.\n` +
    `/** Theme PNGs as base64, keyed by \`ThemeImage\` name: the send path's inline parts. */\n` +
    `export const THEME_PNGS: Record<string, string> = {\n${body}\n};\n`,
);
console.log(`theme-images.ts: ${names.length} images`);
